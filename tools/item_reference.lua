-- Generates docs/ITEMS.md from content/items.xml, content/pocketitems.xml and the English EID text.
--
--   lua5.4 tools/item_reference.lua .          (writes docs/ITEMS.md)
--   lua5.4 tools/item_reference.lua . --check  (fails if docs/ITEMS.md is stale)

local root, mode = arg[1] or ".", arg[2]
function include(name) return dofile(root .. "/" .. name:gsub("%.", "/") .. ".lua") end

local function idsFrom(start)
    local ids, nxt = {}, start
    return function(n)
        if not ids[n] then ids[n] = nxt; nxt = nxt + 1 end
        return ids[n]
    end
end
local savedIsaac, savedEid = Isaac, EID
Isaac = {
    GetItemIdByName = idsFrom(800),
    GetTrinketIdByName = idsFrom(190),
    GetPlayerTypeByName = function(n, tainted) return 0 end,
    GetPillEffectByName = idsFrom(50),
}
local text = { item = {}, trinket = {}, pill = {} }
local function add(kind) return function(_, id, desc, name, lang) if lang == "en_us" then text[kind][id] = desc end end end
EID = { addCollectible = add("item"), addTrinket = add("trinket"), addPill = add("pill"), addCharacterInfo = function() end }
include("scripts.eid"):Init()

local function read(path) local f = assert(io.open(root .. "/" .. path)); local s = f:read("a"); f:close(); return s end
local function unescape(s) return (s:gsub("&gt;", ">"):gsub("&lt;", "<"):gsub("&quot;", "\""):gsub("&apos;", "'"):gsub("&amp;", "&")) end
local function attr(rest, key) local v = rest:match(key .. "=\"([^\"]*)\"") return v and unescape(v) end
local function cell(s) return (s:gsub("|", "\\|")) end
local function effect(desc)
    desc = desc:gsub("{{ArrowUp}}%s*", ""):gsub("{{ArrowDown}}%s*", "")
    return cell(desc:gsub("#", "; "))
end

local actives, passives, trinkets, pills = {}, {}, {}, {}
for tag, name, rest in read("content/items.xml"):gmatch("<(%a+)%s+name=\"([^\"]+)\"([^>]*)>") do
    name = unescape(name)
    local row = { name = name, pickup = attr(rest, "description"), quality = attr(rest, "quality"), charges = attr(rest, "maxcharges"), chargetype = attr(rest, "chargetype") }
    if tag == "trinket" then
        row.eid = text.trinket[Isaac.GetTrinketIdByName(name)]
        trinkets[#trinkets + 1] = row
    else
        row.eid = text.item[Isaac.GetItemIdByName(name)]
        if tag == "active" then actives[#actives + 1] = row else passives[#passives + 1] = row end
    end
end
for name in read("content/pocketitems.xml"):gmatch("<pilleffect%s+name=\"([^\"]+)\"") do
    name = unescape(name)
    pills[#pills + 1] = { name = name, eid = text.pill[Isaac.GetPillEffectByName(name)] }
end
Isaac, EID = savedIsaac, savedEid

local byName = function(a, b) return a.name:lower() < b.name:lower() end
for _, list in ipairs({ actives, passives, trinkets, pills }) do table.sort(list, byName) end

local out = {}
local function line(s) out[#out + 1] = s or "" end
line("# Item reference")
line()
line("Generated by `tools/item_reference.lua` from `content/items.xml`, `content/pocketitems.xml` and the English text in `scripts/eid.lua`. Do not edit by hand; run `lua5.4 tools/item_reference.lua .` after changing an item.")
line()
line("The pickup line is what the game shows when you pick the item up. The effect column is the External Item Descriptions (EID) text, shown in game when EID is installed. Effects describe the current source; most have not been verified in the engine yet (see docs/TESTING.md).")
line()
line(("%d collectibles (%d active, %d passive), %d trinkets and %d pills."):format(#actives + #passives, #actives, #passives, #trinkets, #pills))
local function section(title, list, withCharge)
    line()
    line("## " .. title)
    line()
    if withCharge then
        line("| Item | Pickup line | Quality | Charge | Effect |")
        line("|---|---|---|---|---|")
    elseif list == pills then
        line("| Pill | Effect |")
        line("|---|---|")
    else
        line("| Item | Pickup line" .. (list == trinkets and "" or " | Quality") .. " | Effect |")
        line("|---|---|" .. (list == trinkets and "" or "---|") .. "---|")
    end
    for _, r in ipairs(list) do
        local eid = assert(r.eid, "no English EID text for " .. r.name)
        if withCharge then
            local charge = r.chargetype == "timed" and "timed" or (r.charges .. " rooms")
            line(("| %s | %s | %s | %s | %s |"):format(cell(r.name), cell(r.pickup), r.quality, charge, effect(eid)))
        elseif list == pills then
            line(("| %s | %s |"):format(cell(r.name), effect(eid)))
        elseif list == trinkets then
            line(("| %s | %s | %s |"):format(cell(r.name), cell(r.pickup), effect(eid)))
        else
            line(("| %s | %s | %s | %s |"):format(cell(r.name), cell(r.pickup), r.quality, effect(eid)))
        end
    end
end
section("Active items", actives, true)
section("Passive items", passives)
section("Trinkets", trinkets)
section("Pills", pills)
local doc = table.concat(out, "\n") .. "\n"

local target = root .. "/docs/ITEMS.md"
if mode == "--check" then
    local f = io.open(target)
    local current = f and f:read("a")
    if f then f:close() end
    assert(current == doc, "docs/ITEMS.md is stale: run lua5.4 tools/item_reference.lua .")
    print("docs/ITEMS.md is up to date")
else
    local f = assert(io.open(target, "w")); f:write(doc); f:close()
    print("wrote " .. target)
end
